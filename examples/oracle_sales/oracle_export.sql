  CREATE OR REPLACE EDITIONABLE PROCEDURE "SALES"."P_ARCHIVE_ORDERS" (p_before IN DATE) AS
    v_count NUMBER := 0;
  BEGIN
    FOR r IN (SELECT order_id FROM sales.orders WHERE order_date < p_before) LOOP
      INSERT INTO sales.orders_archive SELECT * FROM sales.orders WHERE order_id = r.order_id;
      DELETE FROM sales.orders WHERE order_id = r.order_id;
      v_count := v_count + 1;
    END LOOP;
    COMMIT;
    DBMS_OUTPUT.PUT_LINE('Archived ' || v_count);
  END p_archive_orders;
