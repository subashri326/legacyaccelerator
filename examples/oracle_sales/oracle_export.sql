  CREATE OR REPLACE FORCE EDITIONABLE VIEW "SALES"."V_ORDER_SUMMARY" ("ORDER_ID", "CUSTOMER_LABEL", "ORDER_DAY", "DUE_DATE", "STATUS_TEXT", "NET_AMOUNT", "NOTE_FLAG", "EMAIL_PREFIX") AS
  SELECT o.order_id,
         c.full_name || ' (' || c.segment || ')',
         TRUNC(o.order_date),
         o.order_date + 30,
         DECODE(o.status, 'N', 'New', 'S', 'Shipped', NULL, 'Unknown', 'Other'),
         o.amount - NVL(o.discount, 0),
         CASE WHEN o.note = '' THEN 'EMPTY' WHEN o.note IS NULL THEN 'NONE' ELSE 'TEXT' END,
         SUBSTR(c.email, 0, 3)
    FROM sales.orders o
    JOIN sales.customers c ON c.customer_id = o.customer_id;

  CREATE OR REPLACE FORCE EDITIONABLE VIEW "SALES"."V_CUSTOMER_ACTIVITY" ("CUSTOMER_ID", "FULL_NAME", "ORDER_COUNT", "LAST_ORDER_MONTH") AS
  SELECT c.customer_id, c.full_name, COUNT(o.order_id), MAX(TO_CHAR(o.order_date, 'YYYY-MM'))
    FROM sales.customers c, sales.orders o
   WHERE c.customer_id = o.customer_id(+)
   GROUP BY c.customer_id, c.full_name;

  CREATE OR REPLACE FORCE EDITIONABLE VIEW "SALES"."V_TOP_ORDERS" ("ORDER_ID", "AMOUNT") AS
  SELECT order_id, amount FROM (SELECT order_id, amount FROM sales.orders ORDER BY amount DESC)
   WHERE ROWNUM <= 5;

  CREATE OR REPLACE FORCE EDITIONABLE VIEW "SALES"."V_RECENT_ORDERS" ("ORDER_ID", "ORDER_DATE") AS
  SELECT order_id, order_date FROM sales.orders WHERE order_date >= '01-MAR-26';

