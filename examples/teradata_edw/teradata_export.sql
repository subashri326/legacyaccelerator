/* SHOW TABLE / SHOW VIEW output for database EDW, Teradata Vantage 17.20 */

CREATE SET TABLE EDW.CUSTOMER_DIM ,FALLBACK ,
     NO BEFORE JOURNAL,
     NO AFTER JOURNAL,
     CHECKSUM = DEFAULT,
     DEFAULT MERGEBLOCKRATIO,
     MAP = TD_MAP1
     (
      CUST_ID INTEGER NOT NULL,
      CUST_NM VARCHAR(100) CHARACTER SET LATIN NOT CASESPECIFIC NOT NULL,
      SEG_CD CHAR(3) CHARACTER SET LATIN CASESPECIFIC COMPRESS ('ENT','SMB'),
      CITY_NM VARCHAR(60) CHARACTER SET UNICODE NOT CASESPECIFIC,
      BIRTH_DT DATE FORMAT 'YYYY-MM-DD',
      SCORE BYTEINT,
      LOAD_TS TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP(6))
UNIQUE PRIMARY INDEX ( CUST_ID )
INDEX IX_SEG ( SEG_CD );

CREATE MULTISET TABLE EDW.SALES_FACT ,NO FALLBACK ,
     NO BEFORE JOURNAL,
     NO AFTER JOURNAL,
     CHECKSUM = DEFAULT,
     DEFAULT MERGEBLOCKRATIO,
     MAP = TD_MAP1
     (
      SALE_ID BIGINT NOT NULL,
      CUST_ID INTEGER NOT NULL,
      SALE_DT DATE FORMAT 'YY/MM/DD' NOT NULL,
      QTY INTEGER NOT NULL,
      UNITS_PER_BOX INTEGER NOT NULL,
      AMT DECIMAL(18,2) COMPRESS 0.00 )
PRIMARY INDEX ( CUST_ID )
PARTITION BY RANGE_N(SALE_DT  BETWEEN DATE '2025-01-01' AND DATE '2027-12-31' EACH INTERVAL '1' MONTH );

CREATE MULTISET TABLE EDW.SALES_MART ,NO FALLBACK
     (
      CUST_ID INTEGER NOT NULL,
      TOTAL_AMT DECIMAL(18,2),
      SALE_CNT INTEGER)
UNIQUE PRIMARY INDEX ( CUST_ID );

REPLACE VIEW EDW.V_SALES_SUMMARY AS LOCKING ROW FOR ACCESS
SEL f.SALE_ID, f.CUST_ID, c.CUST_NM,
    ZEROIFNULL(f.AMT) AS AMT,
    f.QTY / f.UNITS_PER_BOX AS BOXES,
    f.SALE_DT + 7 AS DUE_DT,
    NULLIFZERO(f.QTY) AS QTY_OR_NULL
FROM EDW.SALES_FACT f
INNER JOIN EDW.CUSTOMER_DIM c ON f.CUST_ID = c.CUST_ID
WHERE c.CUST_NM LIKE 'customer%'
QUALIFY ROW_NUMBER() OVER (PARTITION BY f.CUST_ID ORDER BY f.SALE_ID DESC) <= 3;

REPLACE VIEW EDW.V_CITY_COUNTS AS LOCKING ROW FOR ACCESS
SEL c.CITY_NM, COUNT(*) AS CUSTOMERS
FROM EDW.CUSTOMER_DIM c
GROUP BY 1;

REPLACE VIEW EDW.V_SAMPLE_SALES AS
SEL SALE_ID, AMT FROM EDW.SALES_FACT SAMPLE 10;

REPLACE PROCEDURE EDW.SP_REBUILD_MART()
BEGIN
  DECLARE v_cnt INTEGER DEFAULT 0;
  DELETE FROM EDW.SALES_MART;
  INSERT INTO EDW.SALES_MART SELECT CUST_ID, SUM(AMT), COUNT(*) FROM EDW.SALES_FACT GROUP BY 1;
  SET v_cnt = ACTIVITY_COUNT;
  IF v_cnt = 0 THEN
    SIGNAL SQLSTATE '75000' SET MESSAGE_TEXT = 'empty mart';
  END IF;
END;
